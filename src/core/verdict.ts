/**
 * Разбор результата — «что это значит».
 *
 * Итоговый экран показывает цифры, но цифра сама по себе ничего не
 * объясняет: 60% — это много или мало, и что с этим делать? Здесь
 * результат раскладывается на три независимых качества проверяющего
 * и каждое получает словесную оценку и совет.
 *
 * Все функции чистые и покрыты тестами: формулировки — часть содержания
 * игры, и менять их случайно нельзя.
 */
import type { Totals } from './types';

/** Уровень по шкале: чем выше, тем лучше сработал игрок. */
export type VerdictLevel = 'low' | 'mid' | 'high';

export interface VerdictBand {
  level: VerdictLevel;
  /** Короткий вывод: что означает такой результат. */
  title: string;
  /** Развёрнутое объяснение — чем такой проверяющий опасен или хорош. */
  meaning: string;
  /** Что конкретно делать дальше. */
  advice: string;
}

export interface VerdictSection {
  id: 'decisions' | 'detection' | 'caution';
  /** Название качества. */
  caption: string;
  /** Фактическое значение словами: «7 из 10». */
  value: string;
  /** Оценка, приведённая к десятибалльной шкале, — по ней выбран порог. */
  score: number;
  /** Пояснение, по какому числу выставлена оценка. */
  basis: string;
  band: VerdictBand;
}

/**
 * Пороги одинаковы для всех трёх шкал: до 6 — низкий уровень,
 * 6–7 — средний, 8 и выше — высокий. Так игроку не нужно держать
 * в голове три разные системы оценок.
 */
export const VERDICT_THRESHOLDS = { mid: 6, high: 8 } as const;

export function levelFor(score: number): VerdictLevel {
  if (score >= VERDICT_THRESHOLDS.high) return 'high';
  if (score >= VERDICT_THRESHOLDS.mid) return 'mid';
  return 'low';
}

