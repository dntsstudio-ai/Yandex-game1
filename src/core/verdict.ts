/** Значение, приведённое к десятибалльной шкале; 0 знаменатель — 0 баллов. */
export function scaleTo10(value: number, total: number): number {
  if (total <= 0) return 0;
  return Math.round((value / total) * 10);
}

/**
 * Разбор партии по трём качествам. Порядок секций постоянный:
 * решение, внимательность, аккуратность — от итога к причинам.
 */
export function buildVerdict(totals: Totals): VerdictSection[] {
  const rounds = Math.max(1, totals.roundsPlayed);

  const decisionScore = scaleTo10(totals.correctDecisions, rounds);
  const detectionScore = totals.totalFlags > 0 ? scaleTo10(totals.found, totals.totalFlags) : 10;

  // Лишние отметки считаются на десять документов, чтобы короткая партия
  // не выглядела аккуратнее длинной просто из-за меньшего числа кликов.
  const falsePer10 = (totals.falsePositives / rounds) * 10;
  const cautionScore = Math.max(0, 10 - Math.round(falsePer10 * 1.5));

  return [
    {
      id: 'decisions',
      caption: 'Решения по документам',
      value: `${totals.correctDecisions} из ${totals.roundsPlayed}`,
      score: decisionScore,
      basis: 'сколько раз «пропустить» или «остановить» оказалось верным',
      band: DECISIONS[levelFor(decisionScore)],
    },
    {
      id: 'detection',
      caption: 'Внимательность',
      value: `${totals.found} из ${totals.totalFlags} признаков`,
      score: detectionScore,
      basis: 'какая доля красных флагов была найдена',
      band: DETECTION[levelFor(detectionScore)],
    },
    {
      id: 'caution',
      caption: 'Аккуратность',
      value:
        totals.falsePositives === 0
          ? 'ни одной лишней отметки'
          : `${totals.falsePositives} ${plural(totals.falsePositives, 'лишняя отметка', 'лишние отметки', 'лишних отметок')}`,
      score: cautionScore,
      basis: 'сколько нормальных фрагментов было отмечено как нарушение',
      band: CAUTION[levelFor(cautionScore)],
    },
  ];
}

/**
 * Общий вывод: по самой слабой из трёх шкал.
 * Средним значением слабое место сглаживалось бы, а разбор нужен именно
 * ради него.
 */
export function verdictSummary(sections: readonly VerdictSection[]): string {
  const weakest = [...sections].sort((a, b) => a.score - b.score)[0];
  if (!weakest) return '';
  if (weakest.score >= VERDICT_THRESHOLDS.high) {
    return 'Слабых мест в этой проверке нет — все три качества на высоком уровне.';
  }
  return `Главное, над чем стоит поработать: ${weakest.caption.toLowerCase()}.`;
}

function plural(count: number, one: string, few: string, many: string): string {
  const mod100 = count % 100;
  if (mod100 >= 11 && mod100 <= 14) return many;
  const mod10 = count % 10;
  if (mod10 === 1) return one;
  if (mod10 >= 2 && mod10 <= 4) return few;
  return many;
}
